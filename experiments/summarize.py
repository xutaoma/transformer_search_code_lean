"""Write results/summary.md: acceptance table and hand-off numbers, all read from results/."""
import json, pathlib
import numpy as np
HERE = pathlib.Path(__file__).resolve().parent
RES = HERE / "results"


def J(name):
    p = RES / name
    return json.loads(p.read_text()) if p.exists() else None


def chk(ok):
    return "PASS" if ok else "**FAIL**"


def main(cfg):
    A1, A2, B, Bd, D = J("A1_slopes.json"), J("A2_slopes.json"), J("B_exponents.json"), J("B_diagnostics.json"), J("D_ablation.json")
    L = ["# Results summary (generated by `run.py --exp summary`)", ""]
    N = cfg["A"]["N"]; r = (N - 1) / N
    targets = [("a2", 2, .05), ("b1", 2, .05), ("g1-d1", 1, .05), ("g2-d2", 1, .05), ("g1", r, .03), ("g2", r, .03), ("d1", -1 / N, .01), ("d2", -1 / N, .01)]
    L += ["## Experiment A: growth rates (N=16, K=8)", "",
          "| quantity | target | A1 slope (fit t in [1e3,1e9]) | | A2 slope (fit t in [1e3,%s]) | |" % (f"{A2['horizon_t']:g}" if A2 else "-"), "|---|---|---|---|---|---|"]
    for k, tg, tol in targets:
        a = A1["slopes"][k]
        row = f"| {k} | {tg:.4f} +- {tol} | {a['slope']:.4f} (se {a['se']:.4f}) | {chk(abs(a['slope'] - tg) <= tol)} |"
        if A2:
            b = A2["slopes"][k]
            row += f" {b['slope']:.4f} (se {b['se']:.4f}) | {chk(abs(b['slope'] - tg) <= tol)} |"
        else:
            row += " pending | |"
        L.append(row)
    L += ["", "| check | criterion | A1 | |" + (" A2 | |" if A2 else ""), "|---|---|---|---|" + ("---|---|" if A2 else "")]
    def line(name, crit, a, ok, b=None, okb=None):
        s = f"| {name} | {crit} | {a} | {chk(ok)} |"
        if A2:
            s += f" {b} | {chk(okb)} |" if b is not None else " - | |"
        L.append(s)
    line("min u", ">= -1e-6", f"{A1['min_u']:.3g}", A1["min_u"] >= -1e-6, f"{A2['min_u']:.3g}" if A2 else None, A2 and A2["min_u"] >= -1e-6)
    line("sup u", "< 10", f"{A1['sup_u']:.3f}", A1["sup_u"] < 10, f"{A2['sup_u']:.3f}" if A2 else None, A2 and A2["sup_u"] < 10)
    line("sup |v|", "< 2", f"{A1['sup_abs_v']:.3f}", A1["sup_abs_v"] < 2, f"{A2['sup_abs_v']:.3f}" if A2 else None, A2 and A2["sup_abs_v"] < 2)
    line("drift of g1+(N-1)d1", "< 1e-6", f"{A1['conservation_err_g1']:.2e}", A1["conservation_err_g1"] < 1e-6)
    if A2:
        sd = max(A2["subspace_distance_sup"].values()); md = max(A2["max_abs_diff_to_A1"].values())
        line("sup subspace distance", "< 1e-2", "-", True, f"{sd:.2e}", sd < 1e-2)
        line("max |scalar - A1| at matched t", "< 0.1", "-", True, f"{md:.3f}", md < 0.1)
    L += ["", f"Hand-off time (first t with b2<=0 and d2<=0): A1 {A1['handoff_t']:.3g}" + (f", A2 {A2['handoff_t']:.3g}" if A2 else "") + ".",
          f"A1 final values at t=1e9: " + ", ".join(f"{k}={v:.4f}" for k, v in A1["final"].items()) + ".",
          f"ODE regularisation: max |theta(eps)-theta(1e-6)|: {A1['eps_sensitivity_max_abs']}; literal GD eta=0.05 vs ODE for t in [1,5e5]: {A1['euler_vs_ode_max_abs']:.4f}.", ""]
    if B:
        e = B["A1"]["exponents"]
        L += ["## Experiment B: generalization (reduced model; test set of %d prefixes)" % B["A1"]["n_prefixes"], "",
              "| quantity | target | exponent on [1e3,1e9] | |" + (" A2 on [1e3,5e5] |" if "A2" in B else ""), "|---|---|---|---|" + ("---|" if "A2" in B else "")]
        for k, tg, tol in (("mean_forward", -1, .05), ("mean_backtrack_nonroot", -1, .05), ("mean_backtrack_root", -r, .03), ("L_gen", -r, .03)):
            row = f"| {k} | {tg:.4f} +- {tol} | {e[k]['slope']:.4f} | {chk(abs(e[k]['slope'] - tg) <= tol)} |"
            if "A2" in B:
                row += f" {B['A2']['exponents'][k]['slope']:.4f} |"
            L.append(row)
        a = B["A1"]
        L += ["", f"Accuracy = 1 for t>=100: {chk(a['acc_at_t_ge_100'] == 1)} (minimum over t>=100 is {a['acc_at_t_ge_100']:.4f}; accuracy is 1 from t={a['acc_one_from_t']:.3g}).",
              f"Prefix attaining L_gen at t=1e9: category `{a['argmax_final']['category']}`, graph kind `{a['argmax_final']['kind']}`, loss {a['argmax_final']['loss']:.3g} (plan expected `backtrack_root`).",
              f"Decomposition logit(parent=root)-(g1-d1+d2): {a['decomposition']}.", ""]
        if "A2" in B:
            b = B["A2"]
            L += [f"A2 check: accuracy min for t>=100 {b['acc_at_t_ge_100']:.4f}; L_gen prefix at final t: `{b['argmax_final']['category']}`.", ""]
    if Bd:
        L += ["### Diagnostic: forward steps split by back-edge (n_t -> stack parent is an edge)", "",
              f"Prefix counts: {Bd['counts']}.", "", "| group | " + " | ".join(Bd["exponents"]) + " |", "|---|" + "---|" * len(Bd["exponents"])]
        for k in next(iter(Bd["exponents"].values())):
            L.append(f"| {k} | " + " | ".join(f"{Bd['exponents'][w][k]:.4f}" for w in Bd["exponents"]) + " |")
        L += ["", f"Accuracy reaches 1 from t = {Bd['accuracy_one_from']}.",
              f"L_gen attained by a forward back-edge step at every checked t up to 1e16: {Bd['L_gen_category_at']}. Crude extrapolated crossover with backtrack_root: t ~ {Bd['extrapolated_crossover_t_backedge_vs_root']:.2g} (not observed; float64 stops the flow at about 3e16).", ""]
    p = RES / "C_exponents.csv"
    if p.exists():
        rows = np.genfromtxt(p, delimiter=",", names=True)
        L += ["## Experiment C: exponent vs N (fit t in [1e4,1e9])", "", "| N | K | fitted | theory | diff | |", "|---|---|---|---|---|---|"]
        for x in rows:
            L.append(f"| {int(x['N'])} | {int(x['K'])} | {x['fitted']:.4f} | {x['theory']:.4f} | {x['diff']:+.4f} | {chk(abs(x['diff']) <= .02)} |")
        L.append("")
    if D:
        L += ["## Experiment D: initialisation ablation", "", "| run | model | init | R'(0) | first t in region | stays from t | max(b2-b1) | min b1 | final g1-d1 |", "|---|---|---|---|---|---|---|---|---|"]
        for k, v in D.items():
            f = v["final"]
            L.append(f"| {k} | {v['model']} | {v['init']} | {v['relu0']} | {v['first_in_region_t']} | {v['stays_in_region_from_t']} | {v['max_b2_minus_b1']:.3g} | {v['min_b1']:.3g} | {f['g1'] - f['d1']:.3f} |")
        L.append("")
    note = HERE / "DEVIATIONS.md"
    if note.exists():
        L += [note.read_text()]
    L += ["## Figures", "",
          "- `fig_rates_main.pdf`: a2, b1 grow with slope 2 in ln t and g1-d1, g2-d2 with slope 1; lines are the reduced flow, markers the full-matrix run.",
          "- `fig_rates_individual.pdf`: g1, g2 follow (N-1)/N and d1, d2 follow -1/N; g1+(N-1)d1 is conserved and g2+(N-1)d2 is flat after an initial phase.",
          "- `fig_gaps.pdf`: u and 2(g1-d1)-a2 stay bounded; v, b2 and a1 stay small after the initial phase.",
          "- `fig_subspace.pdf`: full-matrix sampled GD stays close to the permutation-invariant subspace.",
          "- `fig_gen_decay.pdf`: per-category mean admissible-token loss and L_gen against t, with fitted exponents.",
          "- `fig_gen_accuracy.pdf`: test accuracy against t; forward steps with a back-edge are the last group to reach 1.",
          "- `fig_exponent_vs_N.pdf`: fitted backtrack-root exponent follows -(N-1)/N for N from 8 to 32.",
          "- `fig_init_wrong_side.pdf`: D2 exits on the wrong side at (16,2) and (40,3) and recovers, but not at (16,8); D3 freezes g1-d1 at all three.",
          "- `fig_init_ablation.pdf`: constant initialisation with R'(0)=0 freezes g1-d1 under exact heads, while round-off or sampling noise can release it.", ""]
    (RES / "summary.md").write_text("\n".join(L))
    print("\n".join(L))
